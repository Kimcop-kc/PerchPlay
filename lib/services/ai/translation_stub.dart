/// ─────────────────────────────────────────────────────────────
///
/// 目标：为已下载的 MADLAD-400 GGUF 模型提供端侧翻译推理。
///
/// TL;DR：**不可行。** 本项目 Dart 3.4.4 无法使用任何 pub.dev 上的
/// GGUF 推理包。要启用翻译功能，**必须先升级 Flutter SDK**。
///
/// ─────────────────────────────────────────────────────────────
/// 1. 实测结果
/// ─────────────────────────────────────────────────────────────
///
/// ## fllamer 0.2.2（父 agent 推荐）
///   命令:   `flutter pub add fllamer`
///   结果:   ❌ "SDK version >=3.11.5 <4.0.0"
///   详情:   发布在 pub.dev/packages/fllamer，由 orcalogy.com 维护。
///           内置 llama.cpp CMake 编译，支持 Android arm64。
///           但 SDK ^3.11.5 差距太大（本项目 Dart 3.4.4）。
///   许可:   GPL-3.0
///
/// ## llamadart 0.14.0
///   命令:   未尝试（SDK ^3.10.7 已超出范围）
///   详情:   pub.dev/packages/llamadart，leehack.com，49 likes。
///           同样需要 Dart 3.10.7+。
///
/// ## llama_cpp_flutter 0.8.0
///   详情:   pub.dev/packages/llama_cpp_flutter，jamiewest.dev。
///           Android 明确标 "Not yet" —— 不支持。
///
/// ─────────────────────────────────────────────────────────────
/// 2. 根因分析
/// ─────────────────────────────────────────────────────────────
///
///   Dart 3.4 是 2024 年中的版本。GGUF 推理包普遍要求 Dart 3.7+
///   因为它们在 2025-2026 年间才开始出现，依赖了新版 ffi、native_assets、
///   hooks 等 package 里 break 过的 API。
///
///   本项目被锁在 Dart 3.4.4 的原因是：
///     media_kit_libs_android_video: 1.3.7（compileSdk 31）
///     ← Flutter 3.22.3（Dart 3.4.4）
///     ← AGP 8.1 的 aapt2 处理不了 compileSdk 36
///
/// ─────────────────────────────────────────────────────────────
/// 3. 可行路径（按推荐度排序）
/// ─────────────────────────────────────────────────────────────
///
///   A) 升级 Flutter → fllamer 0.2.2
///      - 升级 Flutter 到 3.47+（Dart 3.11+）
///      - media_kit 最新版已支持 compileSdk 36
///      - fllamer 支持 GGUF 推理 + embedding + RAG
///      - 风险：GPL-3.0 许可是否与商业发布兼容
///
///   B) 升级 Flutter → llamadart 0.14.0
///      - 升级 Flutter 到 3.38+（Dart 3.10+）
///      - llamadart 社区更大（49 likes vs 0 likes）
///      - 风险：需确认 Android Vulkan 后端稳定性
///
///   C) 云端翻译 API（不升级 Flutter 的唯一可行方案）
///      - 用 http 调 LibreTranslate / Google Translate API
///      - 放弃端侧离线卖点
///      - 立即可用，零新增依赖
///
///   D) 手动编译 llama.cpp .so + dart:ffi 绑定
///      - 工作量大（≥400 行绑定 + C 头文件）
///      - 不推荐：维护成本高，生态里已有成熟包
///
/// ─────────────────────────────────────────────────────────────
/// 4. 结论
/// ─────────────────────────────────────────────────────────────
///
///   在当前 Dart 3.4.4 / Flutter 3.22.3 / Android arm64 环境下，
///   不存在任何 pub.dev 包能支持本地 GGUF 推理。
///
///   最务实的路径：先确认 media_kit 最新版 → 升级 Flutter → fllamer。
///   MADLAD-400 模型文件可正常下载，等推理后端 ready 后直接用。
/// ─────────────────────────────────────────────────────────────
///
